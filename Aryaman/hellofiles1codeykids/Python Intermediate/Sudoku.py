import turtle
# GAME LOGIC
#Sudoku grid 9 nubers below it click a square then click the number to place it there.

t = turtle.Turtle()

# Basic settings
CELL_SIZE = 40      
GRID_SIZE = 9       
LINE_COLOR = "black"

turtle.speed(0)
turtle.hideturtle()
turtle.color(LINE_COLOR)

def jump_to(x, y):
    turtle.penup()
    turtle.goto(x, y)
    turtle.pendown()

def draw_line(x1, y1, x2, y2, width=1):
    turtle.width(width)
    jump_to(x1, y1)
    turtle.goto(x2, y2)

def draw_sudoku_grid():
    total_size = CELL_SIZE * GRID_SIZE      
    half = total_size / 2

    for i in range(GRID_SIZE + 1):
        x = -half + i * CELL_SIZE
        w = 3 if i % 3 == 0 else 1
        draw_line(x, -half, x, half, width=w)

    for i in range(GRID_SIZE + 1):
        y = -half + i * CELL_SIZE
        w = 3 if i % 3 == 0 else 1
        draw_line(-half, y, half, y, width=w)


