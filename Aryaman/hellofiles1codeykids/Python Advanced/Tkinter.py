import tkinter as tk

root = tk.Tk()

# Keep track of the text ID so we can delete the old one on the next click
coord_text_id = None

def print_loc(event):
    global coord_text_id
    
    # 1. Print to the console (optional)
    print(event.x, event.y)
    
    # 2. Delete the previously drawn text if it exists
    if coord_text_id:
        c.delete(coord_text_id)
        
    # 3. Draw the new coordinates right next to your mouse pointer
    coord_text = f"X: {event.x}, Y: {event.y}"
    coord_text_id = c.create_text(event.x + 15, event.y, text=coord_text, anchor="w", fill="black", font=("Arial", 10, "bold"))

c = tk.Canvas(root, width=600, height=600, bg="white")
c.pack()

# Bind the click event to the canvas 'c' instead of 'root' for more accurate canvas coordinates
c.bind("<Button-1>", print_loc)

c.create_rectangle(20, 20, 580, 580, outline="gold", width=40)
